## EXTAPI Python wrapper: `<plugin>_ext.py`, written by `registerExtPlugin`
## under `-d:BrokerFfiApiGenPy`.
##
## The plugin side of an EXTAPI plugin (doc/design/EXTAPI_PLAN.md §8,
## Python), for lib mode: a Python application hosting a Nim library gets the
## host table from `<lib>_extHost()` and implements the plugin in-process.
##   `<Plugin>` base class — override methods; `async def` methods run on the
##       asyncio loop given to `Port.open` (Nim cancel / deadline →
##       `task.cancel()`), plain `def` methods reply inline on the host's thread
##   `Builder` — per-name callables; provides exactly what is set
##   `Port` (open / provide / withdraw / close) and `Emitter`.
## An exception in plugin code becomes an error reply. Separate from the
## `(API)` `<lib>.py`.

{.push raises: [].}

import std/[strutils, macros]
import ./ext_brokers, ./api_codegen_cbor_py

proc pascalPy(s: string): string {.compileTime.} =
  var cap = true
  for ch in s:
    if ch == '_':
      cap = true
    elif cap:
      result.add(toUpperAscii(ch))
      cap = false
    else:
      result.add(ch)

proc pyType(t, plugin: string): string {.compileTime.} =
  let h = nimTypeToPyHint(t)
  if h.len == 0 or "Any" in h:
    macros.error(
      "EXTAPI Python codegen (" & plugin & "): Nim type '" & t &
        "' has no Python mapping (EXTAPI v1 maps primitives, string, seq, seq[byte], " &
        "Option, Table and inline payload fields)"
    )
  h

proc generateExtPyFile*(
    plugin, version, schemaHash: string, entries: seq[ExtEntryCT]
): string {.compileTime.} =
  let base = pascalPy(plugin)
  var py = ""
  py.add(
    "# Generated by nim-brokers registerExtPlugin. Do not edit.\n" &
      "\"\"\"Implement the EXTAPI plugin `" & plugin & "` in Python (lib mode).\n\n" &
      "Subclass `" & base & "` and wire it with `Port.open`, or set per-name callables\n" &
      "with `Builder`. The host table comes from the Nim library's\n" &
      "`<lib>_extHost()` export.\n\"\"\"\n\n" & "from __future__ import annotations\n\n" &
      "import asyncio\nimport ctypes\nimport inspect\nimport threading\n" &
      "from dataclasses import dataclass, field, fields\n" &
      "from typing import Any, Callable, Dict, List, Optional\n\n" & "import cbor2\n\n" &
      "PLUGIN = \"" & plugin & "\"\nVERSION = \"" & version & "\"\nSCHEMA_HASH = \"" &
      schemaHash & "\"\n\n" & "ABI_VERSION = 1\n" &
      "OK, BAD_ARG, UNKNOWN_NAME, AGAIN, SHUTDOWN = 0, -1, -4, -6, -11\n" &
      "SCHEMA_MISMATCH, STALE, ALREADY_PROVIDED, NOT_PROVIDED, DISPATCH_MISMATCH = -14, -15, -16, -17, -18\n" &
      "_REPLY_OK, _REPLY_ERR = 0, 1\n_CAP_NONBLOCKING, _CAP_REPLY_INLINE = 1, 2\n\n"
  )
  # ctypes mirror of broker_ext.h
  py.add(
    "# broker_ext.h, mirrored. Field order is ABI.\n" &
      "_INVOKE_FN = ctypes.CFUNCTYPE(None, ctypes.c_void_p, ctypes.c_uint64, ctypes.c_uint32, ctypes.c_char_p, ctypes.POINTER(ctypes.c_uint8), ctypes.c_size_t)\n" &
      "_CANCEL_FN = ctypes.CFUNCTYPE(None, ctypes.c_void_p, ctypes.c_uint64)\n" &
      "_RELEASE_FN = ctypes.CFUNCTYPE(None, ctypes.c_void_p)\n\n\n" &
      "class _Impl(ctypes.Structure):\n    _fields_ = [\n" &
      "        (\"abiVersion\", ctypes.c_uint32),\n        (\"plugin\", ctypes.c_char_p),\n" &
      "        (\"schemaHash\", ctypes.c_char_p),\n        (\"caps\", ctypes.c_uint32),\n" &
      "        (\"invoke\", _INVOKE_FN),\n        (\"cancel\", _CANCEL_FN),\n" &
      "        (\"release\", _RELEASE_FN),\n        (\"user\", ctypes.c_void_p),\n    ]\n\n\n" &
      "class _Host(ctypes.Structure):\n    _fields_ = [\n" &
      "        (\"abiVersion\", ctypes.c_uint32),\n        (\"host\", ctypes.c_void_p),\n" &
      "        (\"open\", ctypes.CFUNCTYPE(ctypes.c_int32, ctypes.c_void_p, ctypes.c_uint32, ctypes.POINTER(_Impl), ctypes.POINTER(ctypes.c_uint64))),\n" &
      "        (\"close\", ctypes.CFUNCTYPE(ctypes.c_int32, ctypes.c_void_p, ctypes.c_uint64)),\n" &
      "        (\"provide\", ctypes.CFUNCTYPE(ctypes.c_int32, ctypes.c_void_p, ctypes.c_uint64, ctypes.c_char_p)),\n" &
      "        (\"withdraw\", ctypes.CFUNCTYPE(ctypes.c_int32, ctypes.c_void_p, ctypes.c_uint64, ctypes.c_char_p)),\n" &
      "        (\"reply\", ctypes.CFUNCTYPE(ctypes.c_int32, ctypes.c_void_p, ctypes.c_uint64, ctypes.c_uint64, ctypes.c_int32, ctypes.c_char_p, ctypes.c_size_t)),\n" &
      "        (\"emit\", ctypes.CFUNCTYPE(ctypes.c_int32, ctypes.c_void_p, ctypes.c_uint64, ctypes.c_char_p, ctypes.c_char_p, ctypes.c_size_t)),\n" &
      "        (\"listApis\", ctypes.c_void_p),\n        (\"getSchema\", ctypes.c_void_p),\n" &
      "        (\"freeBuffer\", ctypes.c_void_p),\n        (\"schemaHash\", ctypes.c_void_p),\n    ]\n\n\n" &
      "def _host_ptr(host: Any) -> Any:\n" &
      "    \"\"\"Accepts an int address, a c_void_p or a POINTER(_Host).\"\"\"\n" &
      "    if isinstance(host, ctypes.POINTER(_Host)):\n        return host\n" &
      "    addr = host.value if isinstance(host, ctypes.c_void_p) else int(host)\n" &
      "    if not addr:\n        raise ValueError(\"nil host table\")\n" &
      "    return ctypes.cast(ctypes.c_void_p(addr), ctypes.POINTER(_Host))\n\n\n"
  )
  # Types.
  var emitted: seq[string]
  for e in entries:
    if e.payloadType != "void" and e.payloadFields.len > 0 and
        e.payloadType notin emitted:
      emitted.add(e.payloadType)
      py.add("@dataclass\nclass " & e.payloadType & ":\n")
      for (fname, ft) in e.payloadFields:
        py.add(
          "    " & fname & ": " & pyType(ft, plugin) & " = " & nimTypeToPyDefault(ft) &
            "\n"
        )
      py.add("\n\n")
  py.add(
    "def _to_wire(v: Any) -> Any:\n" & "    if hasattr(v, \"__dataclass_fields__\"):\n" &
      "        return {f.name: getattr(v, f.name) for f in fields(v) if getattr(v, f.name) is not None}\n" &
      "    return v\n\n\n" & "def _from_wire(cls: Any, d: Any) -> Any:\n" &
      "    if hasattr(cls, \"__dataclass_fields__\"):\n" &
      "        names = {f.name for f in fields(cls)}\n" &
      "        return cls(**{k: v for k, v in (d or {}).items() if k in names})\n" &
      "    return d\n\n\n"
  )

  proc valueCls(e: ExtEntryCT): string =
    if e.payloadType == "void":
      "None"
    elif e.payloadFields.len > 0:
      e.payloadType
    else:
      pyType(e.payloadType, plugin)

  proc decodeCls(e: ExtEntryCT): string =
    ## The `cls` argument for _from_wire (None for primitives).
    (if e.payloadFields.len > 0: e.payloadType else: "None")

  # Base class.
  py.add(
    "class " & base &
      ":\n    \"\"\"Override the names this plugin implements. Requests may be\n" &
      "    `async def` (run on the loop given to `Port.open`; a Nim cancel or deadline\n" &
      "    cancels the task) or plain `def` (replies inline on the host's thread).\n" &
      "    Raise to reply with an error. Signals are one-way.\"\"\"\n\n"
  )
  for e in entries:
    case e.kind
    of enkRequest:
      var ps = @["self"]
      for (n, t) in e.args:
        ps.add(n & ": " & pyType(t, plugin))
      py.add(
        "    async def " & e.wireName & "(" & ps.join(", ") & ") -> " & valueCls(e) &
          ":\n        raise NotImplementedError(\"" & e.wireName & "\")\n\n"
      )
    of enkSignal:
      let p = (if e.payloadType == "void": ""
      else: ", v: " & valueCls(e))
      py.add("    def " & e.wireName & "(self" & p & ") -> None:\n        pass\n\n")
    of enkEvent:
      discard
  py.add("\n")

  # Name table: idx -> (wire name, kind, arg names, payload decode class)
  py.add(
    "# idx -> (wire name, is_request, arg names, signal payload class or None)\n_NAMES = {\n"
  )
  for i, e in entries:
    case e.kind
    of enkRequest:
      var an: seq[string]
      for (n, _) in e.args:
        an.add("\"" & n & "\"")
      py.add(
        "    " & $i & ": (\"" & e.wireName & "\", True, [" & an.join(", ") &
          "], None),\n"
      )
    of enkSignal:
      let cls = (if e.payloadType == "void": "\"void\""
      else: decodeCls(e))
      py.add("    " & $i & ": (\"" & e.wireName & "\", False, [], " & cls & "),\n")
    of enkEvent:
      discard
  py.add("}\nAPIS = [n for (n, _, _, _) in _NAMES.values()]\n\n")

  # Live ports: ctypes callbacks must outlive the host's use of them.
  py.add(
    "_LIVE: Dict[int, \"Port\"] = {}\n_LIVE_LOCK = threading.Lock()\n_NEXT = [1]\n\n\n" &
      "class Emitter:\n    \"\"\"Emits the plugin's events; thread-safe. After close every emit\n" &
      "    returns STALE.\"\"\"\n\n" &
      "    def __init__(self, host: Any, port: int) -> None:\n        self._host = host\n        self._port = port\n\n" &
      "    def _raw(self, name: bytes, v: Any) -> int:\n" &
      "        if self._host is None:\n            return STALE\n" &
      "        b = b\"\" if v is None else cbor2.dumps(_to_wire(v))\n" &
      "        h = self._host.contents\n" &
      "        return h.emit(h.host, self._port, name, b, len(b))\n\n"
  )
  for e in entries:
    if e.kind != enkEvent:
      continue
    if e.payloadType == "void":
      py.add(
        "    def " & e.wireName & "(self) -> int:\n        return self._raw(b\"" &
          e.wireName & "\", None)\n\n"
      )
    else:
      py.add(
        "    def " & e.wireName & "(self, v: " & valueCls(e) &
          ") -> int:\n        return self._raw(b\"" & e.wireName & "\", v)\n\n"
      )
  py.add("\n")

  # Port.
  py.add(
    "class Port:\n    \"\"\"An open port of this plugin on one broker context.\"\"\"\n\n" &
      "    def __init__(self, host: Any, handlers: Dict[str, Callable[..., Any]], loop: Optional[asyncio.AbstractEventLoop]) -> None:\n" &
      "        self._host = _host_ptr(host)\n        self._handlers = handlers\n        self._loop = loop\n" &
      "        self._port = 0\n        self._closed = False\n        self._pending: Dict[int, Any] = {}\n" &
      "        self._lock = threading.Lock()\n" &
      "        self._cb_invoke = _INVOKE_FN(self._invoke)\n        self._cb_cancel = _CANCEL_FN(self._cancel)\n" &
      "        self._cb_release = _RELEASE_FN(self._release)\n" &
      "        with _LIVE_LOCK:\n            self._key = _NEXT[0]\n            _NEXT[0] += 1\n            _LIVE[self._key] = self\n\n" &
      "    @staticmethod\n    def open(host: Any, ctx: int, impl: " & base &
      ", loop: Optional[asyncio.AbstractEventLoop] = None) -> \"Port\":\n" &
      "        \"\"\"Wire an implementation. Provide names afterwards (provide / provide_all).\"\"\"\n" &
      "        handlers = {n: getattr(impl, n) for n in APIS}\n" &
      "        return Port._open(host, ctx, handlers, loop)\n\n" &
      "    @staticmethod\n    def _open(host: Any, ctx: int, handlers: Dict[str, Callable[..., Any]], loop: Optional[asyncio.AbstractEventLoop]) -> \"Port\":\n" &
      "        p = Port(host, handlers, loop)\n" &
      "        impl = _Impl(ABI_VERSION, PLUGIN.encode(), SCHEMA_HASH.encode(), _CAP_NONBLOCKING,\n" &
      "                     p._cb_invoke, p._cb_cancel, p._cb_release, ctypes.c_void_p(p._key))\n" &
      "        out = ctypes.c_uint64(0)\n        h = p._host.contents\n" &
      "        rc = h.open(h.host, ctx, ctypes.byref(impl), ctypes.byref(out))\n" &
      "        if rc != OK:\n            with _LIVE_LOCK:\n                _LIVE.pop(p._key, None)\n" &
      "            raise RuntimeError(f\"open failed: {rc}\")\n" &
      "        p._port = out.value\n        return p\n\n" &
      "    def provide(self, name: str) -> int:\n" &
      "        if self._closed:\n            return STALE\n        h = self._host.contents\n" &
      "        return h.provide(h.host, self._port, name.encode())\n\n" &
      "    def withdraw(self, name: str) -> int:\n" &
      "        if self._closed:\n            return STALE\n        h = self._host.contents\n" &
      "        return h.withdraw(h.host, self._port, name.encode())\n\n" &
      "    def provide_all(self) -> int:\n        for n in APIS:\n            rc = self.provide(n)\n" &
      "            if rc != OK:\n                return rc\n        return OK\n\n" &
      "    def emitter(self) -> Emitter:\n" &
      "        return Emitter(None if self._closed else self._host, self._port)\n\n" &
      "    @property\n    def handle(self) -> int:\n        return self._port\n\n" &
      "    def close(self) -> None:\n        \"\"\"Withdraw every name and invalidate the port. Idempotent.\"\"\"\n" &
      "        if self._closed:\n            return\n        self._closed = True\n" &
      "        h = self._host.contents\n        h.close(h.host, self._port)\n\n" &
      "    # -- trampolines (host threads; ctypes takes the GIL) --\n\n" &
      "    def _reply(self, call_id: int, status: int, b: bytes) -> None:\n" &
      "        if call_id == 0:\n            return\n        h = self._host.contents\n" &
      "        h.reply(h.host, self._port, call_id, status, b, len(b))\n\n" &
      "    def _reply_value(self, call_id: int, v: Any) -> None:\n" &
      "        try:\n            b = b\"\" if v is None else cbor2.dumps(_to_wire(v))\n" &
      "        except Exception as e:  # noqa: BLE001\n" &
      "            self._reply(call_id, _REPLY_ERR, f\"encode: {e}\".encode())\n            return\n" &
      "        self._reply(call_id, _REPLY_OK, b)\n\n" &
      "    def _invoke(self, _user: Any, call_id: int, idx: int, _name: Any, buf: Any, n: int) -> None:\n" &
      "        try:\n            entry = _NAMES.get(idx)\n            fn = self._handlers.get(entry[0]) if entry else None\n" &
      "            if fn is None:\n                self._reply(call_id, _REPLY_ERR, b\"not implemented by plugin\")\n                return\n" &
      "            data = ctypes.string_at(buf, n) if n else b\"\"\n" &
      "            _, is_request, arg_names, sig_cls = entry\n" &
      "            if not is_request:\n" &
      "                args = () if sig_cls == \"void\" else (_from_wire(sig_cls, cbor2.loads(data)),)\n" &
      "                if inspect.iscoroutinefunction(fn):\n" &
      "                    if self._loop is not None:\n" &
      "                        asyncio.run_coroutine_threadsafe(fn(*args), self._loop)\n" &
      "                else:\n                    fn(*args)\n                return\n" &
      "            d = cbor2.loads(data) if data else {}\n" &
      "            kwargs = {a: d.get(a) for a in arg_names}\n" &
      "            if inspect.iscoroutinefunction(fn):\n" &
      "                if self._loop is None:\n" &
      "                    self._reply(call_id, _REPLY_ERR, b\"async handler needs a loop (Port.open(..., loop=...))\")\n" &
      "                    return\n" &
      "                fut = asyncio.run_coroutine_threadsafe(fn(**kwargs), self._loop)\n" &
      "                with self._lock:\n                    self._pending[call_id] = fut\n" &
      "                fut.add_done_callback(lambda f, cid=call_id: self._done(cid, f))\n" &
      "            else:\n                self._reply_value(call_id, fn(**kwargs))\n" &
      "        except BaseException as e:  # noqa: BLE001\n" &
      "            self._reply(call_id, _REPLY_ERR, f\"plugin error: {e}\".encode())\n\n" &
      "    def _done(self, call_id: int, fut: Any) -> None:\n" &
      "        with self._lock:\n            self._pending.pop(call_id, None)\n" &
      "        if fut.cancelled():\n            return  # cancelled by Nim: the reply would be dropped anyway\n" &
      "        e = fut.exception()\n        if e is not None:\n" &
      "            self._reply(call_id, _REPLY_ERR, str(e).encode())\n        else:\n" &
      "            self._reply_value(call_id, fut.result())\n\n" &
      "    def _cancel(self, _user: Any, call_id: int) -> None:\n" &
      "        with self._lock:\n            fut = self._pending.pop(call_id, None)\n" &
      "        if fut is not None:\n            fut.cancel()\n\n" &
      "    def _release(self, _user: Any) -> None:\n" &
      "        # The host no longer calls this port: drop the keep-alive reference.\n" &
      "        with _LIVE_LOCK:\n            _LIVE.pop(self._key, None)\n\n\n"
  )

  # Builder.
  py.add(
    "class Builder:\n    \"\"\"Wire individual names with callables (sync or async); `open`\n" &
      "    provides exactly the names that were set.\"\"\"\n\n" &
      "    def __init__(self) -> None:\n        self._handlers: Dict[str, Callable[..., Any]] = {}\n\n"
  )
  for e in entries:
    if e.kind != enkEvent:
      py.add(
        "    def " & e.wireName & "(self, fn: Callable[..., Any]) -> \"Builder\":\n" &
          "        self._handlers[\"" & e.wireName & "\"] = fn\n        return self\n\n"
      )
  py.add(
    "    def open(self, host: Any, ctx: int, loop: Optional[asyncio.AbstractEventLoop] = None) -> Port:\n" &
      "        p = Port._open(host, ctx, dict(self._handlers), loop)\n" &
      "        for n in self._handlers:\n            rc = p.provide(n)\n" &
      "            if rc != OK:\n                p.close()\n                raise RuntimeError(f\"provide {n} failed: {rc}\")\n" &
      "        return p\n"
  )
  py

