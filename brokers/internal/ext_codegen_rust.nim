## EXTAPI Rust wrapper: the `<plugin>_ext_rs/` crate, written by
## `registerExtPlugin` under `-d:BrokerFfiApiGenRust`.
##
## The plugin side of an EXTAPI plugin (doc/design/EXTAPI_PLAN.md §8):
##   R1  `<Plugin>` trait with `async fn` requests (runtime-agnostic: futures
##       run on a caller-supplied `Spawn`; cancellation = the future is
##       dropped via `futures::future::Abortable`)
##   R2  `<Plugin>Sync` trait: blocking methods with a `CancelFlag`, served
##       with BROKER_EXT_CAP_REPLY_INLINE (inplace / workers brokers)
##   R4  `Builder`: per-name closures; provides exactly what is set
## plus `Port` (open / provide / withdraw / close, Drop) and `Emitter`.
## Panics in plugin code become `Err` replies. Separate from the `(API)`
## `<lib>_rs` crate.

{.push raises: [].}

import std/[strutils, macros]
import ./ext_brokers, ./ext_runtime, ./api_codegen_cbor_rust

proc upperCamelRs(s: string): string {.compileTime.} =
  var cap = true
  for ch in s:
    if ch == '_':
      cap = true
    elif cap:
      result.add(toUpperAscii(ch))
      cap = false
    else:
      result.add(ch)

proc rsType(t, plugin: string): string {.compileTime.} =
  if rustTableNeedsKeyConv(t):
    macros.error(
      "EXTAPI Rust codegen (" & plugin &
        "): non-string Table keys are not supported yet ('" & t & "')"
    )
  let r = nimTypeToRustHint(t)
  if r.len == 0 or "serde_cbor_value" in r:
    macros.error(
      "EXTAPI Rust codegen (" & plugin & "): Nim type '" & t &
        "' has no Rust mapping (EXTAPI v1 maps primitives, string, seq, seq[byte], " &
        "Option, Table[string, T] and inline payload fields)"
    )
  r

proc isBytes(t: string): bool {.compileTime.} =
  t.strip().toLowerAscii() == "seq[byte]"

proc isOpt(t: string): bool {.compileTime.} =
  t.strip().toLowerAscii().startsWith("option[")

proc emitRsStruct(
    rs: var string,
    name: string,
    fields: seq[(string, string)],
    plugin: string,
    public: bool,
) {.compileTime.} =
  let vis = (if public: "pub " else: "pub(crate) ")
  rs.add(
    "#[derive(Serialize, Deserialize, Clone, Debug, Default, PartialEq)]\n" & vis &
      "struct " & name & " {\n"
  )
  for (fname, ft) in fields:
    if isBytes(ft):
      rs.add("    #[serde(with = \"serde_bytes\")]\n")
    elif isOpt(ft):
      rs.add("    #[serde(default, skip_serializing_if = \"Option::is_none\")]\n")
    rs.add("    pub " & fname & ": " & rsType(ft, plugin) & ",\n")
  rs.add("}\n\n")

proc generateExtRustCrate*(
    plugin, version, schemaHash: string, entries: seq[ExtEntryCT]
): tuple[cargo: string, lib: string] {.compileTime.} =
  let crate = plugin & "_ext"
  let traitName = upperCamelRs(plugin)
  result.cargo =
    "# Generated by nim-brokers registerExtPlugin. Do not edit.\n[package]\nname = \"" &
    crate & "\"\nversion = \"" & version &
    "\"\nedition = \"2021\"\nrust-version = \"1.75\"\n\n[lib]\npath = \"src/lib.rs\"\n\n" &
    "[dependencies]\nciborium = \"0.2\"\nserde = { version = \"1\", features = [\"derive\"] }\n" &
    "serde_bytes = \"0.11\"\nfutures = \"0.3\"\n"

  var rs = ""
  rs.add(
    "//! `" & crate &
      "` — generated by nim-brokers `registerExtPlugin`. Do not edit.\n" &
      "//! Implement the EXTAPI plugin `" & plugin &
      "` in Rust: an async trait (R1), a sync\n" &
      "//! trait (R2) or per-name closures (R4); wire it with `Port` / `Builder`.\n\n" &
      "#![allow(dead_code, clippy::all)]\n\n" & "use std::collections::HashMap;\n" &
      "use std::ffi::{c_char, c_void};\nuse std::future::Future;\n" &
      "use std::panic::{catch_unwind, AssertUnwindSafe};\n" &
      "use std::sync::atomic::{AtomicBool, AtomicU64, Ordering};\n" &
      "use std::sync::{Arc, Mutex};\n\n" &
      "use futures::future::{AbortHandle, Abortable, BoxFuture, FutureExt};\n" &
      "use serde::{de::DeserializeOwned, Deserialize, Serialize};\n\n"
  )
  rs.add(
    "pub const PLUGIN: &str = \"" & plugin & "\";\npub const VERSION: &str = \"" &
      version & "\";\npub const SCHEMA_HASH: &str = \"" & schemaHash & "\";\n" &
      "const PLUGIN_C: &[u8] = b\"" & plugin & "\\0\";\nconst SCHEMA_HASH_C: &[u8] = b\"" &
      schemaHash & "\\0\";\n\n" &
      "pub const ABI_VERSION: u32 = 1;\npub const OK: i32 = 0;\n" &
      "pub const BAD_ARG: i32 = -1;\npub const UNKNOWN_NAME: i32 = -4;\npub const AGAIN: i32 = -6;\n" &
      "pub const SHUTDOWN: i32 = -11;\npub const SCHEMA_MISMATCH: i32 = -14;\npub const STALE: i32 = -15;\n" &
      "pub const ALREADY_PROVIDED: i32 = -16;\npub const NOT_PROVIDED: i32 = -17;\n" &
      "pub const DISPATCH_MISMATCH: i32 = -18;\npub const REPLY_OK: i32 = 0;\npub const REPLY_ERR: i32 = 1;\n" &
      "pub const CAP_NONBLOCKING: u32 = 1;\npub const CAP_REPLY_INLINE: u32 = 2;\n\n"
  )
  # FFI mirror of broker_ext.h.
  rs.add(
    "/// `broker_ext.h`, mirrored. Field order is ABI.\npub mod ffi {\n    use std::ffi::{c_char, c_void};\n" &
      "    pub type InvokeFn = unsafe extern \"C\" fn(*mut c_void, u64, u32, *const c_char, *const u8, usize);\n" &
      "    pub type CancelFn = unsafe extern \"C\" fn(*mut c_void, u64);\n" &
      "    pub type ReleaseFn = unsafe extern \"C\" fn(*mut c_void);\n" &
      "    #[repr(C)]\n    pub struct BrokerExtImpl {\n        pub abi_version: u32,\n" &
      "        pub plugin: *const c_char,\n        pub schema_hash: *const c_char,\n" &
      "        pub caps: u32,\n        pub invoke: Option<InvokeFn>,\n        pub cancel: Option<CancelFn>,\n" &
      "        pub release: Option<ReleaseFn>,\n        pub user: *mut c_void,\n    }\n" &
      "    #[repr(C)]\n    pub struct BrokerExtHost {\n        pub abi_version: u32,\n        pub host: *mut c_void,\n" &
      "        pub open: Option<unsafe extern \"C\" fn(*mut c_void, u32, *const BrokerExtImpl, *mut u64) -> i32>,\n" &
      "        pub close: Option<unsafe extern \"C\" fn(*mut c_void, u64) -> i32>,\n" &
      "        pub provide: Option<unsafe extern \"C\" fn(*mut c_void, u64, *const c_char) -> i32>,\n" &
      "        pub withdraw: Option<unsafe extern \"C\" fn(*mut c_void, u64, *const c_char) -> i32>,\n" &
      "        pub reply: Option<unsafe extern \"C\" fn(*mut c_void, u64, u64, i32, *const u8, usize) -> i32>,\n" &
      "        pub emit: Option<unsafe extern \"C\" fn(*mut c_void, u64, *const c_char, *const u8, usize) -> i32>,\n" &
      "        pub list_apis: Option<unsafe extern \"C\" fn(*mut c_void, *const c_char, *mut *mut u8, *mut usize) -> i32>,\n" &
      "        pub get_schema: Option<unsafe extern \"C\" fn(*mut c_void, *const c_char, *mut *mut u8, *mut usize) -> i32>,\n" &
      "        pub free_buffer: Option<unsafe extern \"C\" fn(*mut c_void, *mut u8)>,\n" &
      "        pub schema_hash: Option<unsafe extern \"C\" fn(*mut c_void, *const c_char, *mut c_char) -> i32>,\n" &
      "    }\n}\n\n"
  )
  rs.add(
    "/// The host's function table. Copy, Send + Sync: every entry may be called\n" &
      "/// from any thread.\n#[derive(Clone, Copy)]\npub struct Host(*const ffi::BrokerExtHost);\n" &
      "unsafe impl Send for Host {}\nunsafe impl Sync for Host {}\nimpl Host {\n" &
      "    /// # Safety\n    /// `p` must be the table handed out by the Nim host and outlive the plugin.\n" &
      "    pub unsafe fn from_raw(p: *const ffi::BrokerExtHost) -> Self {\n        Host(p)\n    }\n" &
      "    fn t(&self) -> &ffi::BrokerExtHost {\n        unsafe { &*self.0 }\n    }\n}\n\n"
  )
  # Types.
  var emitted: seq[string]
  for e in entries:
    if e.payloadType != "void" and e.payloadFields.len > 0 and
        e.payloadType notin emitted:
      emitted.add(e.payloadType)
      emitRsStruct(rs, e.payloadType, e.payloadFields, plugin, true)
  for e in entries:
    if e.kind == enkRequest and e.args.len > 0:
      emitRsStruct(rs, upperCamelRs(e.wireName) & "Args", e.args, plugin, false)

  proc valueTy(e: ExtEntryCT): string =
    if e.payloadType == "void":
      "()"
    elif e.payloadFields.len > 0:
      e.payloadType
    else:
      rsType(e.payloadType, plugin)

  # Api enum.
  rs.add(
    "/// Names a port can provide.\n#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]\n#[repr(u32)]\npub enum Api {\n"
  )
  var apis: seq[string]
  for i, e in entries:
    if e.kind != enkEvent:
      rs.add("    " & upperCamelRs(e.wireName) & " = " & $i & ",\n")
      apis.add("Api::" & upperCamelRs(e.wireName))
  rs.add(
    "}\n\nimpl Api {\n    pub fn wire_name(self) -> &'static str {\n        match self {\n"
  )
  for e in entries:
    if e.kind != enkEvent:
      rs.add(
        "            Api::" & upperCamelRs(e.wireName) & " => \"" & e.wireName & "\",\n"
      )
  rs.add(
    "        }\n    }\n    fn c_name(self) -> &'static [u8] {\n        match self {\n"
  )
  for e in entries:
    if e.kind != enkEvent:
      rs.add(
        "            Api::" & upperCamelRs(e.wireName) & " => b\"" & e.wireName &
          "\\0\",\n"
      )
  rs.add(
    "        }\n    }\n    pub fn all() -> &'static [Api] {\n        &[" &
      apis.join(", ") & "]\n    }\n}\n\n"
  )

  # Shared runtime.
  rs.add(
    "/// Where request futures run. Any executor: a closure taking a boxed\n" &
      "/// future (`|f| { tokio::spawn(f); }`, a thread pool, …).\n" &
      "pub trait Spawn: Send + Sync + 'static {\n    fn spawn(&self, fut: BoxFuture<'static, ()>);\n}\n" &
      "impl<F: Fn(BoxFuture<'static, ()>) + Send + Sync + 'static> Spawn for F {\n" &
      "    fn spawn(&self, fut: BoxFuture<'static, ()>) {\n        self(fut)\n    }\n}\n\n" &
      "/// Set when Nim cancels a call (explicit cancel or deadline). R2 methods poll it.\n" &
      "#[derive(Clone, Default)]\npub struct CancelFlag(Arc<AtomicBool>);\nimpl CancelFlag {\n" &
      "    pub fn is_cancelled(&self) -> bool {\n        self.0.load(Ordering::Acquire)\n    }\n}\n\n" &
      "type Dispatch = Box<dyn Fn(&Arc<State>, u64, u32, &[u8]) + Send + Sync>;\n\n" &
      "struct State {\n    host: Host,\n    port: AtomicU64,\n" &
      "    aborts: Mutex<HashMap<u64, AbortHandle>>,\n    flags: Mutex<HashMap<u64, CancelFlag>>,\n" &
      "    dispatch: Dispatch,\n}\n\n" &
      "fn decode<T: DeserializeOwned>(b: &[u8]) -> Result<T, String> {\n" &
      "    ciborium::from_reader(b).map_err(|e| format!(\"decode: {e}\"))\n}\n\n" &
      "fn encode<T: Serialize>(v: &T) -> Result<Vec<u8>, String> {\n" &
      "    let mut out = Vec::new();\n    ciborium::into_writer(v, &mut out).map_err(|e| format!(\"encode: {e}\"))?;\n    Ok(out)\n}\n\n" &
      "fn reply_raw(st: &Arc<State>, id: u64, status: i32, b: &[u8]) {\n" &
      "    if id == 0 {\n        return;\n    }\n    let t = st.host.t();\n" &
      "    if let Some(f) = t.reply {\n        unsafe { f(t.host, st.port.load(Ordering::Acquire), id, status, b.as_ptr(), b.len()) };\n    }\n}\n\n" &
      "fn reply<T: Serialize + 'static>(st: &Arc<State>, id: u64, r: Result<T, String>) {\n" &
      "    match r {\n        Ok(v) => {\n" &
      "            if std::any::TypeId::of::<T>() == std::any::TypeId::of::<()>() {\n" &
      "                reply_raw(st, id, REPLY_OK, &[]);\n                return;\n            }\n" &
      "            match encode(&v) {\n                Ok(b) => reply_raw(st, id, REPLY_OK, &b),\n" &
      "                Err(e) => reply_raw(st, id, REPLY_ERR, e.as_bytes()),\n            }\n        }\n" &
      "        Err(e) => reply_raw(st, id, REPLY_ERR, e.as_bytes()),\n    }\n}\n\n" &
      "fn spawn_request<T, F>(st: &Arc<State>, id: u64, sp: &Arc<dyn Spawn>, fut: F)\nwhere\n" &
      "    T: Serialize + Send + 'static,\n    F: Future<Output = Result<T, String>> + Send + 'static,\n{\n" &
      "    let (handle, reg) = AbortHandle::new_pair();\n    st.aborts.lock().unwrap().insert(id, handle);\n" &
      "    let st2 = st.clone();\n" &
      "    let task = Abortable::new(AssertUnwindSafe(fut).catch_unwind(), reg);\n" &
      "    sp.spawn(\n        async move {\n            match task.await {\n" &
      "                Ok(Ok(r)) => reply(&st2, id, r),\n" &
      "                Ok(Err(p)) => reply_raw(&st2, id, REPLY_ERR, panic_msg(p).as_bytes()),\n" &
      "                Err(_aborted) => {} // cancelled by Nim: the reply would be dropped anyway\n" &
      "            }\n            st2.aborts.lock().unwrap().remove(&id);\n        }\n        .boxed(),\n    );\n}\n\n" &
      "/// The panic payload's message (`panic!(\"…\")` gives a &str or a String).\n" &
      "fn panic_msg(p: Box<dyn std::any::Any + Send>) -> String {\n" &
      "    let m = p.downcast_ref::<&str>().map(|s| s.to_string())\n" &
      "        .or_else(|| p.downcast_ref::<String>().cloned())\n" &
      "        .unwrap_or_else(|| \"unknown\".to_string());\n" &
      "    format!(\"plugin panicked: {m}\")\n}\n\n" &
      "fn cancel_flag(st: &Arc<State>, id: u64) -> CancelFlag {\n" &
      "    let f = CancelFlag::default();\n    st.flags.lock().unwrap().insert(id, f.clone());\n    f\n}\n\n" &
      "unsafe extern \"C\" fn tramp_invoke(user: *mut c_void, id: u64, idx: u32, _n: *const c_char, buf: *const u8, len: usize) {\n" &
      "    let st: &Arc<State> = &*(user as *const Arc<State>);\n" &
      "    let bytes: &[u8] = if buf.is_null() || len == 0 { &[] } else { std::slice::from_raw_parts(buf, len) };\n" &
      "    if let Err(p) = catch_unwind(AssertUnwindSafe(|| (st.dispatch)(st, id, idx, bytes))) {\n" &
      "        reply_raw(st, id, REPLY_ERR, panic_msg(p).as_bytes());\n    }\n}\n\n" &
      "unsafe extern \"C\" fn tramp_cancel(user: *mut c_void, id: u64) {\n" &
      "    let st: &Arc<State> = &*(user as *const Arc<State>);\n" &
      "    if let Some(h) = st.aborts.lock().unwrap().remove(&id) {\n        h.abort();\n    }\n" &
      "    if let Some(f) = st.flags.lock().unwrap().get(&id) {\n        f.0.store(true, Ordering::Release);\n    }\n}\n\n" &
      "unsafe extern \"C\" fn tramp_release(user: *mut c_void) {\n" &
      "    drop(Box::from_raw(user as *mut Arc<State>));\n}\n\n"
  )

  # Emitter.
  rs.add(
    "/// Emits the plugin's events. Clone + Send + Sync; after `close` every emit\n" &
      "/// returns `STALE`.\n#[derive(Clone)]\npub struct Emitter {\n    host: Host,\n    port: u64,\n}\n\nimpl Emitter {\n" &
      "    fn raw(&self, name: &[u8], b: &[u8]) -> i32 {\n        if self.host.0.is_null() {\n            return STALE;\n        }\n        let t = self.host.t();\n" &
      "        match t.emit {\n            Some(f) => unsafe { f(t.host, self.port, name.as_ptr() as *const c_char, b.as_ptr(), b.len()) },\n" &
      "            None => BAD_ARG,\n        }\n    }\n"
  )
  for e in entries:
    if e.kind != enkEvent:
      continue
    if e.payloadType == "void":
      rs.add(
        "    pub fn " & e.wireName & "(&self) -> i32 {\n        self.raw(b\"" &
          e.wireName & "\\0\", &[])\n    }\n"
      )
    else:
      rs.add(
        "    pub fn " & e.wireName & "(&self, v: &" & valueTy(e) & ") -> i32 {\n" &
          "        match encode(v) {\n            Ok(b) => self.raw(b\"" & e.wireName &
          "\\0\", &b),\n            Err(_) => BAD_ARG,\n        }\n    }\n"
      )
  rs.add("}\n\n")

  proc argList(e: ExtEntryCT): string =
    var parts: seq[string]
    for (n, t) in e.args:
      parts.add(n & ": " & rsType(t, plugin))
    parts.join(", ")

  proc argMoves(e: ExtEntryCT): string =
    var parts: seq[string]
    for (n, _) in e.args:
      parts.add("a." & n)
    parts.join(", ")

  proc argTypes(e: ExtEntryCT): string =
    var parts: seq[string]
    for (_, t) in e.args:
      parts.add(rsType(t, plugin))
    parts.join(", ")

  proc decodeArgs(e: ExtEntryCT): string =
    if e.args.len == 0:
      ""
    else:
      "                let a: " & upperCamelRs(e.wireName) &
        "Args = match decode(bytes) { Ok(a) => a, Err(m) => { reply_raw(st, id, REPLY_ERR, m.as_bytes()); return; } };\n"

  proc sigParam(e: ExtEntryCT): string =
    (if e.payloadType == "void": "" else: "v: " & valueTy(e))

  # R1 async trait.
  rs.add(
    "/// R1: implement the plugin as an async trait. Futures run on the\n" &
      "/// `Spawn` given to `Port::open`; a Nim cancel / deadline drops the future.\n" &
      "/// Signals are one-way and should return quickly.\npub trait " & traitName &
      ": Send + Sync + 'static {\n"
  )
  for e in entries:
    case e.kind
    of enkRequest:
      let a = argList(e)
      rs.add(
        "    fn " & e.wireName & "(&self" & (if a.len > 0: ", " & a else: "") &
          ") -> impl Future<Output = Result<" & valueTy(e) & ", String>> + Send;\n"
      )
    of enkSignal:
      let p = sigParam(e)
      rs.add(
        "    fn " & e.wireName & "(&self" & (if p.len > 0: ", " & p else: "") & ");\n"
      )
    of enkEvent:
      discard
  rs.add("}\n\n")
  # R2 sync trait.
  rs.add(
    "/// R2: blocking methods; served with `CAP_REPLY_INLINE` (inplace / workers\n" &
      "/// brokers). Poll `cancel` in long work.\npub trait " & traitName &
      "Sync: Send + Sync + 'static {\n"
  )
  for e in entries:
    case e.kind
    of enkRequest:
      let a = argList(e)
      rs.add(
        "    fn " & e.wireName & "(&self" & (if a.len > 0: ", " & a else: "") &
          ", cancel: &CancelFlag) -> Result<" & valueTy(e) & ", String>;\n"
      )
    of enkSignal:
      let p = sigParam(e)
      rs.add(
        "    fn " & e.wireName & "(&self" & (if p.len > 0: ", " & p else: "") & ");\n"
      )
    of enkEvent:
      discard
  rs.add("}\n\n")

  # Port.
  rs.add(
    "/// An open port of this plugin on one broker context; `Drop` closes it.\n" &
      "pub struct Port {\n    st: Option<Arc<State>>,\n}\n\nimpl Port {\n" &
      "    fn open_with(host: Host, ctx: u32, caps: u32, dispatch: Dispatch) -> Result<Port, String> {\n" &
      "        let st = Arc::new(State {\n            host,\n            port: AtomicU64::new(0),\n" &
      "            aborts: Mutex::new(HashMap::new()),\n            flags: Mutex::new(HashMap::new()),\n            dispatch,\n        });\n" &
      "        let user = Box::into_raw(Box::new(st.clone())) as *mut c_void;\n" &
      "        let imp = ffi::BrokerExtImpl {\n            abi_version: ABI_VERSION,\n" &
      "            plugin: PLUGIN_C.as_ptr() as *const c_char,\n            schema_hash: SCHEMA_HASH_C.as_ptr() as *const c_char,\n" &
      "            caps,\n            invoke: Some(tramp_invoke),\n            cancel: Some(tramp_cancel),\n" &
      "            release: Some(tramp_release),\n            user,\n        };\n" &
      "        let t = host.t();\n        let mut port = 0u64;\n" &
      "        let rc = match t.open {\n            Some(f) => unsafe { f(t.host, ctx, &imp, &mut port) },\n            None => BAD_ARG,\n        };\n" &
      "        if rc != OK {\n            unsafe { drop(Box::from_raw(user as *mut Arc<State>)) };\n" &
      "            return Err(format!(\"open failed: {rc}\"));\n        }\n" &
      "        st.port.store(port, Ordering::Release);\n        Ok(Port { st: Some(st) })\n    }\n\n"
  )
  # open (R1)
  rs.add(
    "    /// R1: wire an async implementation. Provide names afterwards\n" &
      "    /// (`provide` / `provide_all`).\n" & "    pub fn open<S: " & traitName &
      ", P: Spawn>(host: Host, ctx: u32, imp: Arc<S>, spawner: P) -> Result<Port, String> {\n" &
      "        let sp: Arc<dyn Spawn> = Arc::new(spawner);\n" &
      "        let dispatch: Dispatch = Box::new(move |st, id, idx, bytes| match idx {\n"
  )
  for i, e in entries:
    case e.kind
    of enkRequest:
      rs.add(
        "            " & $i & " => {\n" & decodeArgs(e) &
          "                let imp = imp.clone();\n" &
          "                spawn_request(st, id, &sp, async move { imp." & e.wireName &
          "(" & argMoves(e) & ").await });\n            }\n"
      )
    of enkSignal:
      if e.payloadType == "void":
        rs.add("            " & $i & " => imp." & e.wireName & "(),\n")
      else:
        rs.add(
          "            " & $i & " => {\n                if let Ok(v) = decode::<" &
            valueTy(e) & ">(bytes) {\n                    imp." & e.wireName &
            "(v);\n                }\n            }\n"
        )
    of enkEvent:
      discard
  rs.add(
    "            _ => reply_raw(st, id, REPLY_ERR, b\"unknown name\"),\n        });\n" &
      "        Port::open_with(host, ctx, CAP_NONBLOCKING, dispatch)\n    }\n\n"
  )
  # open_sync (R2)
  rs.add(
    "    /// R2: wire a blocking implementation (replies before returning).\n" &
      "    pub fn open_sync<S: " & traitName &
      "Sync>(host: Host, ctx: u32, imp: Arc<S>) -> Result<Port, String> {\n" &
      "        let dispatch: Dispatch = Box::new(move |st, id, idx, bytes| match idx {\n"
  )
  for i, e in entries:
    case e.kind
    of enkRequest:
      let am = argMoves(e)
      rs.add(
        "            " & $i & " => {\n" & decodeArgs(e) &
          "                let flag = cancel_flag(st, id);\n" &
