## EXTAPI Go wrapper: the `<plugin>_ext_go/` module, written by
## `registerExtPlugin` under `-d:BrokerFfiApiGenGo`.
##
## The plugin side of an EXTAPI plugin (doc/design/EXTAPI_PLAN.md §8, Go):
##   `<Plugin>` interface — requests take a `context.Context` that is cancelled
##       when Nim cancels the call (explicit cancel or deadline); each request
##       runs on its own goroutine, so ports advertise CAP_NONBLOCKING
##   `Funcs` — per-name funcs; `OpenFuncs` provides exactly the non-nil ones
##   `Port` (Open / Provide / Withdraw / Close) and `Emitter`.
## Panics in plugin code become error replies. Separate from the `(API)`
## `<lib>_go` module.

{.push raises: [].}

import std/[strutils, macros]
import ./ext_brokers, ./api_codegen_cbor_go

proc pascalGo(s: string): string {.compileTime.} =
  var cap = true
  for ch in s:
    if ch == '_':
      cap = true
    elif cap:
      result.add(toUpperAscii(ch))
      cap = false
    else:
      result.add(ch)

proc lowerFirst(s: string): string {.compileTime.} =
  if s.len > 0:
    result = toLowerAscii(s[0]) & s[1 ..^ 1]

proc goType(t, plugin: string): string {.compileTime.} =
  if goTableNeedsKeyConv(t):
    macros.error(
      "EXTAPI Go codegen (" & plugin &
        "): non-string Table keys are not supported yet ('" & t & "')"
    )
  let g = nimTypeToGoCborHint(t)
  if g.len == 0:
    macros.error(
      "EXTAPI Go codegen (" & plugin & "): Nim type '" & t &
        "' has no Go mapping (EXTAPI v1 maps primitives, string, seq, seq[byte], " &
        "Option, Table[string, T] and inline payload fields)"
    )
  g

proc emitGoStruct(
    g: var string, name: string, fields: seq[(string, string)], plugin: string
) {.compileTime.} =
  g.add("type " & name & " struct {\n")
  for (fname, ft) in fields:
    let omit =
      (if ft.strip().toLowerAscii().startsWith("option["): ",omitempty" else: "")
    g.add(
      "\t" & goExportedField(fname) & " " & goType(ft, plugin) & " `cbor:\"" & fname &
        omit & "\"`\n"
    )
  g.add("}\n\n")

proc generateExtGoModule*(
    plugin, version, schemaHash: string, entries: seq[ExtEntryCT]
): tuple[gomod, main, exports: string] {.compileTime.} =
  let pkg = plugin & "_ext"
  let iface = pascalGo(plugin)
  let invokeFn = "goExtInvoke_" & plugin
  let cancelFn = "goExtCancel_" & plugin
  let releaseFn = "goExtRelease_" & plugin

  result.gomod =
    "// Generated by nim-brokers registerExtPlugin. Do not edit.\nmodule " & pkg &
    "\n\ngo 1.21\n\nrequire github.com/fxamacker/cbor/v2 v2.7.0\n"

  proc valueTy(e: ExtEntryCT): string =
    if e.payloadType == "void":
      ""
    elif e.payloadFields.len > 0:
      e.payloadType
    else:
      goType(e.payloadType, plugin)

  proc params(e: ExtEntryCT): string =
    var parts = @["ctx context.Context"]
    for (n, t) in e.args:
      parts.add(goSafeParam(n) & " " & goType(t, plugin))
    parts.join(", ")

  proc paramTypes(e: ExtEntryCT): string =
    var parts = @["context.Context"]
    for (_, t) in e.args:
      parts.add(goType(t, plugin))
    parts.join(", ")

  proc results(e: ExtEntryCT): string =
    let v = valueTy(e)
    (if v.len == 0: "error" else: "(" & v & ", error)")

  proc sigParam(e: ExtEntryCT): string =
    (if e.payloadType == "void": "" else: "v " & valueTy(e))

  proc sigType(e: ExtEntryCT): string =
    (if e.payloadType == "void": "" else: valueTy(e))

  # Exports file: only declarations in its preamble (cgo rule for //export).
  var x =
    "// Generated by nim-brokers registerExtPlugin. Do not edit.\n\npackage " & pkg &
    "\n\n"
  x.add("/*\n#include <stdint.h>\n#include <stddef.h>\n*/\nimport \"C\"\n\n")
  x.add("import (\n\t\"runtime/cgo\"\n\t\"unsafe\"\n)\n\n")
  x.add(
    "//export " & invokeFn & "\nfunc " & invokeFn &
      "(user unsafe.Pointer, id C.uint64_t, idx C.uint32_t, name *C.char, buf *C.uint8_t, n C.size_t) {\n" &
      "\tst := cgo.Handle(uintptr(user)).Value().(*portState)\n" &
      "\tvar b []byte\n\tif n > 0 && buf != nil {\n\t\tb = C.GoBytes(unsafe.Pointer(buf), C.int(n))\n\t}\n" &
      "\tst.invoke(uint64(id), uint32(idx), b)\n}\n\n"
  )
  x.add(
    "//export " & cancelFn & "\nfunc " & cancelFn &
      "(user unsafe.Pointer, id C.uint64_t) {\n" &
      "\tcgo.Handle(uintptr(user)).Value().(*portState).cancel(uint64(id))\n}\n\n"
  )
  x.add(
    "//export " & releaseFn & "\nfunc " & releaseFn & "(user unsafe.Pointer) {\n" &
      "\tcgo.Handle(uintptr(user)).Delete()\n}\n"
  )
  result.exports = x

  var g = "// Generated by nim-brokers registerExtPlugin. Do not edit.\n//\n"
  g.add(
    "// Package " & pkg & " implements the EXTAPI plugin `" & plugin &
      "` in Go: implement the\n// " & iface &
      " interface (Open) or set per-name funcs (OpenFuncs).\n"
  )
  g.add("package " & pkg & "\n\n/*\n#cgo CFLAGS: -I${SRCDIR}\n")
  g.add(
    "#include <stdint.h>\n#include <stdlib.h>\n#include \"broker_ext.h\"\n\n" &
      "extern void " & invokeFn &
      "(void*, uint64_t, uint32_t, char*, uint8_t*, size_t);\n" & "extern void " &
      cancelFn & "(void*, uint64_t);\n" & "extern void " & releaseFn & "(void*);\n\n"
  )
  g.add(
    "static int32_t ext_open(const broker_ext_host* h, uint32_t ctx, uint32_t caps, uintptr_t user, broker_ext_port* out) {\n" &
      "\tbroker_ext_impl impl = {BROKER_EXT_ABI_VERSION, \"" & plugin & "\", \"" &
      schemaHash & "\", caps,\n" & "\t\t(broker_ext_invoke_fn)" & invokeFn &
      ", (broker_ext_cancel_fn)" & cancelFn & ", (broker_ext_release_fn)" & releaseFn &
      ", (void*)user};\n" & "\treturn h->open(h->host, ctx, &impl, out);\n}\n" &
      "static int32_t ext_close(const broker_ext_host* h, broker_ext_port p) { return h->close(h->host, p); }\n" &
      "static int32_t ext_provide(const broker_ext_host* h, broker_ext_port p, const char* n) { return h->provide(h->host, p, n); }\n" &
      "static int32_t ext_withdraw(const broker_ext_host* h, broker_ext_port p, const char* n) { return h->withdraw(h->host, p, n); }\n" &
      "static int32_t ext_reply(const broker_ext_host* h, broker_ext_port p, uint64_t id, int32_t st, const uint8_t* b, size_t n) { return h->reply(h->host, p, id, st, b, n); }\n" &
      "static int32_t ext_emit(const broker_ext_host* h, broker_ext_port p, const char* name, const uint8_t* b, size_t n) { return h->emit(h->host, p, name, b, n); }\n*/\nimport \"C\"\n\n"
  )
  g.add(
    "import (\n\t\"context\"\n\t\"errors\"\n\t\"fmt\"\n\t\"runtime/cgo\"\n\t\"sync\"\n\t\"sync/atomic\"\n\t\"unsafe\"\n\n\t\"github.com/fxamacker/cbor/v2\"\n)\n\n"
  )
  g.add(
    "const (\n\tPlugin     = \"" & plugin & "\"\n\tVersion    = \"" & version &
      "\"\n\tSchemaHash = \"" & schemaHash & "\"\n)\n\n" &
      "// Status codes (broker_ext.h).\nconst (\n" &
      "\tOK               int32 = 0\n\tBadArg           int32 = -1\n\tUnknownName      int32 = -4\n" &
      "\tAgain            int32 = -6\n\tShutdown         int32 = -11\n\tSchemaMismatch   int32 = -14\n" &
      "\tStale            int32 = -15\n\tAlreadyProvided  int32 = -16\n\tNotProvided      int32 = -17\n" &
      "\tDispatchMismatch int32 = -18\n)\n\n" &
      "const (\n\treplyOK  = 0\n\treplyErr = 1\n\tcapNonblocking = 1\n)\n\n"
  )
  # Types.
  var emitted: seq[string]
  for e in entries:
    if e.payloadType != "void" and e.payloadFields.len > 0 and
        e.payloadType notin emitted:
      emitted.add(e.payloadType)
      emitGoStruct(g, e.payloadType, e.payloadFields, plugin)
  for e in entries:
    if e.kind == enkRequest and e.args.len > 0:
      emitGoStruct(g, lowerFirst(pascalGo(e.wireName)) & "Args", e.args, plugin)

  # Api enum.
  g.add(
    "// Api names a request or signal a port can provide.\ntype Api uint32\n\nconst (\n"
  )
  for i, e in entries:
    if e.kind != enkEvent:
      g.add("\tApi" & pascalGo(e.wireName) & " Api = " & $i & "\n")
  g.add(
    ")\n\n// WireName is the name on the EXTAPI wire.\nfunc (a Api) WireName() string {\n\tswitch a {\n"
  )
  for e in entries:
    if e.kind != enkEvent:
      g.add(
        "\tcase Api" & pascalGo(e.wireName) & ":\n\t\treturn \"" & e.wireName & "\"\n"
      )
  g.add(
    "\t}\n\treturn \"\"\n}\n\n// AllApis lists every request and signal.\nvar AllApis = []Api{"
  )
  var first = true
  for e in entries:
    if e.kind != enkEvent:
      if not first:
        g.add(", ")
      first = false
      g.add("Api" & pascalGo(e.wireName))
  g.add(
    "}\n\n// C strings for the names, allocated once (never freed).\nvar cNames = map[Api]*C.char{}\n\n" &
      "func init() {\n\tfor _, a := range AllApis {\n\t\tcNames[a] = C.CString(a.WireName())\n\t}\n}\n\n"
  )

  # Interface.
  g.add(
    "// " & iface & " is the plugin implemented in Go. Requests run on their own\n" &
      "// goroutine; ctx is cancelled when Nim cancels the call (explicit cancel or\n" &
      "// deadline), and the reply is dropped. Signals run on the host's thread and\n" &
      "// should return quickly.\ntype " & iface & " interface {\n"
  )
  for e in entries:
    case e.kind
    of enkRequest:
      g.add("\t" & pascalGo(e.wireName) & "(" & params(e) & ") " & results(e) & "\n")
    of enkSignal:
      g.add("\t" & pascalGo(e.wireName) & "(" & sigParam(e) & ")\n")
    of enkEvent:
      discard
  g.add("}\n\n")
  # Funcs.
  g.add(
    "// Funcs wires individual names; OpenFuncs provides exactly the non-nil ones.\ntype Funcs struct {\n"
  )
  for e in entries:
    case e.kind
    of enkRequest:
      g.add(
        "\t" & pascalGo(e.wireName) & " func(" & paramTypes(e) & ") " & results(e) & "\n"
      )
    of enkSignal:
      g.add("\t" & pascalGo(e.wireName) & " func(" & sigType(e) & ")\n")
    of enkEvent:
      discard
  g.add("}\n\n")

  # Runtime.
  g.add(
    "type portState struct {\n\thost     *C.broker_ext_host\n\tport     atomic.Uint64\n" &
      "\tmu       sync.Mutex\n\tcancels  map[uint64]context.CancelFunc\n" &
      "\tdispatch func(st *portState, id uint64, idx uint32, b []byte)\n}\n\n" &
      "func (st *portState) replyRaw(id uint64, status int32, b []byte) {\n" &
      "\tif id == 0 {\n\t\treturn\n\t}\n\tvar p *C.uint8_t\n\tif len(b) > 0 {\n\t\tp = (*C.uint8_t)(unsafe.Pointer(&b[0]))\n\t}\n" &
      "\tC.ext_reply(st.host, C.broker_ext_port(st.port.Load()), C.uint64_t(id), C.int32_t(status), p, C.size_t(len(b)))\n}\n\n" &
      "func (st *portState) replyErr(id uint64, msg string) {\n\tst.replyRaw(id, replyErr, []byte(msg))\n}\n\n" &
      "func (st *portState) invoke(id uint64, idx uint32, b []byte) {\n" &
      "\tdefer func() {\n\t\tif r := recover(); r != nil {\n\t\t\tst.replyErr(id, fmt.Sprintf(\"plugin panicked: %v\", r))\n\t\t}\n\t}()\n" &
      "\tst.dispatch(st, id, idx, b)\n}\n\n" &
      "func (st *portState) cancel(id uint64) {\n\tst.mu.Lock()\n\tc := st.cancels[id]\n\tdelete(st.cancels, id)\n\tst.mu.Unlock()\n" &
      "\tif c != nil {\n\t\tc()\n\t}\n}\n\n" &
      "// spawn runs one request on its own goroutine with a cancellable ctx.\n" &
      "func (st *portState) spawn(id uint64, void bool, f func(ctx context.Context) (any, error)) {\n" &
      "\tctx, cancel := context.WithCancel(context.Background())\n" &
      "\tst.mu.Lock()\n\tst.cancels[id] = cancel\n\tst.mu.Unlock()\n" &
      "\tgo func() {\n\t\tdefer func() {\n\t\t\tif r := recover(); r != nil {\n\t\t\t\tst.replyErr(id, fmt.Sprintf(\"plugin panicked: %v\", r))\n\t\t\t}\n" &
      "\t\t\tst.mu.Lock()\n\t\t\tdelete(st.cancels, id)\n\t\t\tst.mu.Unlock()\n\t\t\tcancel()\n\t\t}()\n" &
      "\t\tv, err := f(ctx)\n\t\tif ctx.Err() != nil {\n\t\t\treturn // cancelled by Nim: the reply would be dropped anyway\n\t\t}\n" &
      "\t\tif err != nil {\n\t\t\tst.replyErr(id, err.Error())\n\t\t\treturn\n\t\t}\n" &
      "\t\tif void {\n\t\t\tst.replyRaw(id, replyOK, nil)\n\t\t\treturn\n\t\t}\n" &
      "\t\tb, err := cbor.Marshal(v)\n\t\tif err != nil {\n\t\t\tst.replyErr(id, \"encode: \"+err.Error())\n\t\t\treturn\n\t\t}\n" &
      "\t\tst.replyRaw(id, replyOK, b)\n\t}()\n}\n\n"
  )

  # Emitter.
  g.add(
    "// Emitter emits the plugin's events; safe from any goroutine. After Close\n" &
      "// every emit returns Stale.\ntype Emitter struct {\n\thost *C.broker_ext_host\n\tport uint64\n}\n\n" &
      "func (e Emitter) raw(name *C.char, b []byte) int32 {\n\tif e.host == nil {\n\t\treturn Stale\n\t}\n" &
      "\tvar p *C.uint8_t\n\tif len(b) > 0 {\n\t\tp = (*C.uint8_t)(unsafe.Pointer(&b[0]))\n\t}\n" &
      "\treturn int32(C.ext_emit(e.host, C.broker_ext_port(e.port), name, p, C.size_t(len(b))))\n}\n\n"
  )
  for e in entries:
    if e.kind != enkEvent:
      continue
    let cvar = "cEvent" & pascalGo(e.wireName)
    g.add("var " & cvar & " = C.CString(\"" & e.wireName & "\")\n\n")
    if e.payloadType == "void":
      g.add(
        "func (e Emitter) " & pascalGo(e.wireName) & "() int32 {\n\treturn e.raw(" & cvar &
          ", nil)\n}\n\n"
      )
    else:
      g.add(
        "func (e Emitter) " & pascalGo(e.wireName) & "(v " & valueTy(e) & ") int32 {\n" &
          "\tb, err := cbor.Marshal(v)\n\tif err != nil {\n\t\treturn BadArg\n\t}\n\treturn e.raw(" &
          cvar & ", b)\n}\n\n"
      )

  # Dispatch from Funcs (the interface path wraps the impl into Funcs).
  g.add(
    "func dispatchFuncs(f Funcs) func(st *portState, id uint64, idx uint32, b []byte) {\n"
  )
  g.add(
    "\treturn func(st *portState, id uint64, idx uint32, b []byte) {\n\t\tswitch idx {\n"
  )
  for i, e in entries:
    let fn = "f." & pascalGo(e.wireName)
    case e.kind
    of enkRequest:
      g.add(
        "\t\tcase " & $i & ":\n\t\t\tif " & fn &
          " == nil {\n\t\t\t\tst.replyErr(id, \"not implemented by plugin\")\n\t\t\t\treturn\n\t\t\t}\n"
      )
      var callArgs = @["ctx"]
      if e.args.len > 0:
        g.add(
          "\t\t\tvar a " & lowerFirst(pascalGo(e.wireName)) & "Args\n" &
            "\t\t\tif err := cbor.Unmarshal(b, &a); err != nil {\n\t\t\t\tst.replyErr(id, \"decode: \"+err.Error())\n\t\t\t\treturn\n\t\t\t}\n"
        )
        for (n, _) in e.args:
          callArgs.add("a." & goExportedField(n))
      let call = fn & "(" & callArgs.join(", ") & ")"
      if valueTy(e).len == 0:
        g.add(
          "\t\t\tst.spawn(id, true, func(ctx context.Context) (any, error) { return nil, " &
            call & " })\n"
        )
      else:
        g.add(
          "\t\t\tst.spawn(id, false, func(ctx context.Context) (any, error) { return " &
            call & " })\n"
        )
    of enkSignal:
      g.add(
        "\t\tcase " & $i & ":\n\t\t\tif " & fn & " == nil {\n\t\t\t\treturn\n\t\t\t}\n"
      )
      if e.payloadType == "void":
        g.add("\t\t\t" & fn & "()\n")
      else:
        g.add(
          "\t\t\tvar v " & valueTy(e) &
            "\n\t\t\tif cbor.Unmarshal(b, &v) == nil {\n\t\t\t\t" & fn & "(v)\n\t\t\t}\n"
        )
    of enkEvent:
      discard
  g.add("\t\tdefault:\n\t\t\tst.replyErr(id, \"unknown name\")\n\t\t}\n\t}\n}\n\n")

  # funcsOf(impl)
  g.add("func funcsOf(impl " & iface & ") Funcs {\n\treturn Funcs{\n")
  for e in entries:
    if e.kind != enkEvent:
      g.add("\t\t" & pascalGo(e.wireName) & ": impl." & pascalGo(e.wireName) & ",\n")
  g.add("\t}\n}\n\n")

  # Port.
  g.add(
    "// Host is the host's function table, from `<lib>_extHost()` or the\n" &
      "// `broker_ext_plugin_entry(host)` argument.\ntype Host struct {\n\tp *C.broker_ext_host\n}\n\n" &
      "// HostFromPtr wraps a `const broker_ext_host*`.\nfunc HostFromPtr(p unsafe.Pointer) Host {\n" &
      "\treturn Host{p: (*C.broker_ext_host)(p)}\n}\n\n" &
      "// Port is an open port of this plugin on one broker context.\ntype Port struct {\n" &
      "\tst     *portState\n\tclosed atomic.Bool\n}\n\n" &
      "func open(h Host, brokerCtx uint32, f Funcs) (*Port, error) {\n" &
      "\tif h.p == nil {\n\t\treturn nil, errors.New(\"nil host table\")\n\t}\n" &
      "\tst := &portState{host: h.p, cancels: map[uint64]context.CancelFunc{}, dispatch: dispatchFuncs(f)}\n" &
      "\thandle := cgo.NewHandle(st)\n\tvar port C.broker_ext_port\n" &
      "\trc := C.ext_open(h.p, C.uint32_t(brokerCtx), capNonblocking, C.uintptr_t(handle), &port)\n" &
      "\tif rc != 0 {\n\t\thandle.Delete()\n\t\treturn nil, fmt.Errorf(\"open failed: %d\", int32(rc))\n\t}\n" &
      "\tst.port.Store(uint64(port))\n\treturn &Port{st: st}, nil\n}\n\n" &
      "// Open wires an implementation of " & iface &
      ". Provide names afterwards\n// (Provide / ProvideAll).\nfunc Open(h Host, brokerCtx uint32, impl " &
      iface & ") (*Port, error) {\n\treturn open(h, brokerCtx, funcsOf(impl))\n}\n\n" &
      "// OpenFuncs wires per-name funcs and provides exactly the non-nil ones.\n" &
      "func OpenFuncs(h Host, brokerCtx uint32, f Funcs) (*Port, error) {\n\tp, err := open(h, brokerCtx, f)\n" &
      "\tif err != nil {\n\t\treturn nil, err\n\t}\n"
  )
  for e in entries:
    if e.kind != enkEvent:
      g.add(
        "\tif f." & pascalGo(e.wireName) & " != nil {\n\t\tif rc := p.Provide(Api" &
          pascalGo(e.wireName) &
          "); rc != OK {\n\t\t\tp.Close()\n\t\t\treturn nil, fmt.Errorf(\"provide " &
          e.wireName & " failed: %d\", rc)\n\t\t}\n\t}\n"
      )
  g.add(
    "\treturn p, nil\n}\n\n" &
      "func (p *Port) Provide(a Api) int32 {\n\tif p.closed.Load() {\n\t\treturn Stale\n\t}\n" &
      "\treturn int32(C.ext_provide(p.st.host, C.broker_ext_port(p.st.port.Load()), cNames[a]))\n}\n\n" &
      "func (p *Port) Withdraw(a Api) int32 {\n\tif p.closed.Load() {\n\t\treturn Stale\n\t}\n" &
      "\treturn int32(C.ext_withdraw(p.st.host, C.broker_ext_port(p.st.port.Load()), cNames[a]))\n}\n\n" &
      "func (p *Port) ProvideAll() int32 {\n\tfor _, a := range AllApis {\n\t\tif rc := p.Provide(a); rc != OK {\n\t\t\treturn rc\n\t\t}\n\t}\n\treturn OK\n}\n\n" &
      "func (p *Port) Emitter() Emitter {\n\tif p.closed.Load() {\n\t\treturn Emitter{}\n\t}\n" &
      "\treturn Emitter{host: p.st.host, port: p.st.port.Load()}\n}\n\n" &
      "func (p *Port) Handle() uint64 {\n\treturn p.st.port.Load()\n}\n\n" &
      "// Close withdraws every name and invalidates the port. Idempotent.\n" &
      "func (p *Port) Close() {\n\tif p.closed.Swap(true) {\n\t\treturn\n\t}\n" &
      "\tC.ext_close(p.st.host, C.broker_ext_port(p.st.port.Load()))\n}\n"
  )
  result.main = g

