## EXTAPI C++ wrapper: `<plugin>_ext.hpp`, written by `registerExtPlugin`.
##
## The plugin side of an EXTAPI plugin (doc/design/EXTAPI_PLAN.md §7):
##   C1  `I<Plugin>` abstract class; requests answer through a move-only
##       `Responder<T>` carrying a `std::stop_token` (cancel / timeout hint)
##   C2  `I<Plugin>Sync` adapter: synchronous virtuals, served with
##       BROKER_EXT_CAP_REPLY_INLINE (inplace / workers brokers)
##   C3  `Builder`: per-name `std::function`s; provides exactly what is set
## plus `Port` (open / provide / withdraw / close, RAII) and `Emitter`.
## The typed layer is a CBOR codec (jsoncons) over the raw tunnel of
## `broker_ext.h`; it is never mixed into the `(API)` `<lib>.hpp`.

{.push raises: [].}

import std/[strutils, macros]
import ./ext_brokers, ./ext_runtime, ./api_codegen_cbor_hpp

proc upperCamel(s: string): string {.compileTime.} =
  let lc = snakeToLowerCamel(s)
  if lc.len > 0:
    result = lc
    result[0] = toUpperAscii(result[0])

proc cppFieldType(t, plugin: string): string {.compileTime.} =
  let c = nimTypeToCppType(t)
  if c.len == 0:
    macros.error(
      "EXTAPI C++ codegen (" & plugin & "): Nim type '" & t &
        "' has no C++ mapping (EXTAPI v1 maps primitives, string, seq, " &
        "seq[byte], Option, Table and inline payload fields)"
    )
  c

proc emitStruct(
    h: var string,
    traits: var string,
    ns, name: string,
    fields: seq[(string, string)],
    plugin: string,
) {.compileTime.} =
  h.add("struct " & name & " {\n")
  var required, optional: seq[string]
  for (fname, ft) in fields:
    h.add("  " & cppFieldType(ft, plugin) & " " & fname & "{};\n")
    if ft.strip().toLowerAscii().startsWith("option["):
      optional.add(fname)
    else:
      required.add(fname)
  h.add("};\n\n")
  if fields.len == 0:
    return
  if optional.len == 0:
    traits.add("JSONCONS_ALL_MEMBER_TRAITS(" & ns & "::" & name)
    for n in required:
      traits.add(", " & n)
    traits.add(")\n")
  else:
    traits.add("JSONCONS_N_MEMBER_TRAITS(" & ns & "::" & name & ", " & $required.len)
    for n in required & optional:
      traits.add(", " & n)
    traits.add(")\n")

proc generateExtCppHeader*(
    plugin, version, schemaHash: string, entries: seq[ExtEntryCT]
): string {.compileTime.} =
  let ns = plugin & "_ext"
  let up = plugin.toUpperAscii()
  let iface = "I" & upperCamel(plugin)
  var h = ""
  var traits = ""
  h.add(
    "// " & plugin &
      "_ext.hpp — generated by nim-brokers registerExtPlugin. Do not edit.\n" &
      "// C++20. Requires jsoncons (header-only) on the include path.\n" &
      "#pragma once\n\n" & "#include \"broker_ext.h\"\n#include \"" & plugin &
      "_ext.h\"\n\n" &
      "#include <jsoncons/json.hpp>\n#include <jsoncons_ext/cbor/cbor.hpp>\n\n" &
      "#include <cstdint>\n#include <exception>\n#include <functional>\n#include <memory>\n#include <mutex>\n" &
      "#include <optional>\n#include <stop_token>\n#include <string>\n#include <string_view>\n" &
      "#include <unordered_map>\n#include <utility>\n#include <vector>\n\n"
  )
  h.add("namespace " & ns & " {\n\n")
  h.add(
    "inline constexpr const char* kPlugin = " & up & "_EXT_PLUGIN;\n" &
      "inline constexpr const char* kVersion = \"" & version & "\";\n" &
      "inline constexpr const char* kSchemaHash = " & up & "_EXT_SCHEMA_HASH;\n\n"
  )
  # Bytes: std::vector<uint8_t> that rides as a CBOR byte string (see the
  # traits after the namespace), exactly like the (API) wrappers.
  h.add(
    "struct Bytes : std::vector<uint8_t> {\n  using std::vector<uint8_t>::vector;\n" &
      "  Bytes() = default;\n" &
      "  explicit Bytes(std::vector<uint8_t> v) : std::vector<uint8_t>(std::move(v)) {}\n};\n\n"
  )
  # Result<T>
  h.add(
    "template <class T> class Result {\npublic:\n" &
      "  static Result ok(T v) { Result r; r.v_ = std::move(v); return r; }\n" &
      "  static Result err(std::string e) { Result r; r.e_ = std::move(e); return r; }\n" &
      "  bool isOk() const { return v_.has_value(); }\n  explicit operator bool() const { return isOk(); }\n" &
      "  T& value() { return *v_; }\n  const T& value() const { return *v_; }\n" &
      "  const std::string& error() const { return e_; }\nprivate:\n" &
      "  std::optional<T> v_;\n  std::string e_;\n};\n\n" &
      "template <> class Result<void> {\npublic:\n" &
      "  static Result ok() { Result r; r.ok_ = true; return r; }\n" &
      "  static Result err(std::string e) { Result r; r.e_ = std::move(e); return r; }\n" &
      "  bool isOk() const { return ok_; }\n  explicit operator bool() const { return ok_; }\n" &
      "  const std::string& error() const { return e_; }\nprivate:\n  bool ok_ = false;\n  std::string e_;\n};\n\n"
  )
  # Payload / args structs.
  var emitted: seq[string]
  for e in entries:
    if e.payloadType != "void" and e.payloadFields.len > 0 and
        e.payloadType notin emitted:
      emitted.add(e.payloadType)
      emitStruct(h, traits, ns, e.payloadType, e.payloadFields, plugin)
  h.add("namespace detail {\n")
  for e in entries:
    if e.kind == enkRequest and e.args.len > 0:
      emitStruct(
        h, traits, ns & "::detail", upperCamel(e.wireName) & "Args", e.args, plugin
      )
  h.add("} // namespace detail\n\n")

  # Api enum (provide-able names).
  h.add("enum class Api : uint32_t {\n")
  for i, e in entries:
    if e.kind != enkEvent:
      h.add("  " & upperCamel(e.wireName) & " = " & $i & ",\n")
  h.add("};\n\ninline const char* apiName(Api a) {\n  switch (a) {\n")
  for i, e in entries:
    if e.kind != enkEvent:
      h.add(
        "  case Api::" & upperCamel(e.wireName) & ": return \"" & e.wireName & "\";\n"
      )
  h.add("  }\n  return \"\";\n}\n\n")

  # Shared port state + Responder.
  h.add(
    "class Port;\nclass Builder;\nclass " & iface & ";\n\nnamespace detail {\n" &
      "struct PortState;\nusing StatePtr = std::shared_ptr<PortState>;\n" &
      "template <class T> std::vector<uint8_t> encode(const T& v) {\n" &
      "  std::vector<uint8_t> out;\n  jsoncons::cbor::encode_cbor(v, out);\n  return out;\n}\n" &
      "template <class T> T decode(const uint8_t* buf, size_t len) {\n" &
      "  return jsoncons::cbor::decode_cbor<T>(std::vector<uint8_t>(buf, buf + len));\n}\n" &
      "inline void replyBytes(const StatePtr& st, broker_ext_call_id id, int32_t status, const std::vector<uint8_t>& b);\n" &
      "inline std::stop_token track(const StatePtr& st, broker_ext_call_id id);\n" &
      "inline void untrack(const StatePtr& st, broker_ext_call_id id);\n" &
      "} // namespace detail\n\n"
  )
  h.add(
    "/// Answers one request exactly once. Move-only; destroying it unanswered\n" &
      "/// replies err(\"dropped\") (except while an exception thrown by the plugin\n" &
      "/// method unwinds: that becomes err(what())). `stop_token()` is signalled when Nim cancels the\n" &
      "/// call or its deadline expires — the reply is then dropped by id.\n" &
      "template <class T> class Responder {\npublic:\n" &
      "  Responder(detail::StatePtr st, broker_ext_call_id id) : st_(std::move(st)), id_(id), stop_(detail::track(st_, id)), uncaught_(std::uncaught_exceptions()) {}\n" &
      "  Responder(Responder&& o) noexcept : st_(std::move(o.st_)), id_(o.id_), stop_(std::move(o.stop_)), done_(o.done_), uncaught_(o.uncaught_) { o.done_ = true; }\n" &
      "  Responder& operator=(Responder&&) = delete;\n  Responder(const Responder&) = delete;\n" &
      "  // Destroyed by an exception unwinding out of the plugin method: leave the\n" &
      "  // reply to the dispatcher's catch, which answers err(what()).\n" &
      "  ~Responder() { if (!done_ && std::uncaught_exceptions() <= uncaught_) err(\"dropped\"); }\n" &
      "  void ok(const T& v) { if (done_) return; done_ = true; detail::replyBytes(st_, id_, BROKER_EXT_REPLY_OK, detail::encode(v)); detail::untrack(st_, id_); }\n" &
      "  void err(std::string_view msg) { if (done_) return; done_ = true; detail::replyBytes(st_, id_, BROKER_EXT_REPLY_ERR, std::vector<uint8_t>(msg.begin(), msg.end())); detail::untrack(st_, id_); }\n" &
      "  std::stop_token stop_token() const { return stop_; }\n" &
      "  bool cancelled() const { return stop_.stop_requested(); }\nprivate:\n" &
      "  detail::StatePtr st_;\n  broker_ext_call_id id_;\n  std::stop_token stop_;\n  bool done_ = false;\n  int uncaught_ = 0;\n};\n\n" &
      "template <> class Responder<void> {\npublic:\n" &
      "  Responder(detail::StatePtr st, broker_ext_call_id id) : st_(std::move(st)), id_(id), stop_(detail::track(st_, id)), uncaught_(std::uncaught_exceptions()) {}\n" &
      "  Responder(Responder&& o) noexcept : st_(std::move(o.st_)), id_(o.id_), stop_(std::move(o.stop_)), done_(o.done_), uncaught_(o.uncaught_) { o.done_ = true; }\n" &
      "  Responder& operator=(Responder&&) = delete;\n  Responder(const Responder&) = delete;\n" &
      "  // Destroyed by an exception unwinding out of the plugin method: leave the\n" &
      "  // reply to the dispatcher's catch, which answers err(what()).\n" &
      "  ~Responder() { if (!done_ && std::uncaught_exceptions() <= uncaught_) err(\"dropped\"); }\n" &
      "  void ok() { if (done_) return; done_ = true; detail::replyBytes(st_, id_, BROKER_EXT_REPLY_OK, {}); detail::untrack(st_, id_); }\n" &
      "  void err(std::string_view msg) { if (done_) return; done_ = true; detail::replyBytes(st_, id_, BROKER_EXT_REPLY_ERR, std::vector<uint8_t>(msg.begin(), msg.end())); detail::untrack(st_, id_); }\n" &
      "  std::stop_token stop_token() const { return stop_; }\n" &
      "  bool cancelled() const { return stop_.stop_requested(); }\nprivate:\n" &
      "  detail::StatePtr st_;\n  broker_ext_call_id id_;\n  std::stop_token stop_;\n  bool done_ = false;\n  int uncaught_ = 0;\n};\n\n"
  )

  # Signatures per name.
  proc argsDecl(e: ExtEntryCT): string =
    var parts: seq[string]
    for (n, t) in e.args:
      parts.add(cppFieldType(t, plugin) & " " & n)
    parts.join(", ")

  proc valueType(e: ExtEntryCT): string =
    ## The C++ type of a payload: a generated struct for inline objects, the
    ## mapped type for POD payloads (`Result[int64]`, `seq[string]`, …).
    if e.payloadType == "void":
      "void"
    elif e.payloadFields.len > 0:
      e.payloadType
    else:
      cppFieldType(e.payloadType, plugin)

  proc respType(e: ExtEntryCT): string =
    valueType(e)

  proc sigValue(e: ExtEntryCT): string =
    (if e.payloadType == "void": "" else: valueType(e) & " v")

  # C1 interface.
  h.add(
    "/// C1: implement the plugin as a class. Request methods get their\n" &
      "/// arguments by value and answer through `r` — now or later, from any\n" &
      "/// thread. Signals are one-way. Declares BROKER_EXT_CAP_NONBLOCKING: keep\n" &
      "/// the methods quick (post work to your executor) for `bridge` brokers.\n" &
      "class " & iface & " {\npublic:\n  virtual ~" & iface & "() = default;\n" &
      "  virtual uint32_t caps() const { return BROKER_EXT_CAP_NONBLOCKING; }\n"
  )
  for e in entries:
    let m = snakeToLowerCamel(e.wireName)
    case e.kind
    of enkRequest:
      let a = argsDecl(e)
      h.add(
        "  virtual void " & m & "(" & (if a.len > 0: a & ", " else: "") & "Responder<" &
          respType(e) & "> r) = 0;\n"
      )
    of enkSignal:
      h.add("  virtual void " & m & "(" & sigValue(e) & ") = 0;\n")
    of enkEvent:
      discard
  h.add("};\n\n")
  # C2 sync adapter.
  h.add(
    "/// C2: synchronous adapter. Return the value; served with\n" &
      "/// BROKER_EXT_CAP_REPLY_INLINE (inplace / workers brokers).\n" & "class " & iface &
      "Sync : public " & iface & " {\npublic:\n" &
      "  uint32_t caps() const override { return BROKER_EXT_CAP_REPLY_INLINE; }\n"
  )
  for e in entries:
    if e.kind != enkRequest:
      continue
    let m = snakeToLowerCamel(e.wireName)
    var params: seq[string]
    var names: seq[string]
    for (n, t) in e.args:
      params.add("const " & cppFieldType(t, plugin) & "& " & n)
      names.add(n)
    params.add("std::stop_token st")
    h.add(
      "  virtual Result<" & respType(e) & "> " & m & "Sync(" & params.join(", ") &
        ") = 0;\n"
    )
    var vparams: seq[string]
    for (n, t) in e.args:
      vparams.add(cppFieldType(t, plugin) & " " & n)
    vparams.add("Responder<" & respType(e) & "> r")
    let call = m & "Sync(" & (names & @["r.stop_token()"]).join(", ") & ")"
    if e.payloadType == "void":
      h.add(
        "  void " & m & "(" & vparams.join(", ") & ") final {\n    auto res = " & call &
          ";\n    if (res.isOk()) r.ok(); else r.err(res.error());\n  }\n"
      )
    else:
      h.add(
        "  void " & m & "(" & vparams.join(", ") & ") final {\n    auto res = " & call &
          ";\n    if (res.isOk()) r.ok(res.value()); else r.err(res.error());\n  }\n"
      )
  h.add("};\n\n")

  # Emitter.
  h.add(
    "/// Emits the plugin's events. Copyable, any thread. After the port is\n" &
      "/// closed every emit returns BROKER_EXT_STALE.\n" &
      "class Emitter {\npublic:\n  Emitter() = default;\n" &
      "  Emitter(const broker_ext_host* h, broker_ext_port p) : host_(h), port_(p) {}\n" &
      "  bool valid() const { return host_ != nullptr && port_ != 0; }\n"
  )
  for e in entries:
    if e.kind != enkEvent:
      continue
    let m = snakeToLowerCamel(e.wireName)
    if e.payloadType == "void":
      h.add(
        "  int32_t " & m & "() const {\n    if (!valid()) return BROKER_EXT_STALE;\n" &
          "    return host_->emit(host_->host, port_, \"" & e.wireName &
          "\", nullptr, 0);\n  }\n"
      )
    else:
      h.add(
        "  int32_t " & m & "(const " & valueType(e) & "& v) const {\n" &
          "    if (!valid()) return BROKER_EXT_STALE;\n" &
          "    auto b = detail::encode(v);\n" &
          "    return host_->emit(host_->host, port_, \"" & e.wireName &
          "\", b.data(), b.size());\n  }\n"
      )
  h.add(
    "private:\n  const broker_ext_host* host_ = nullptr;\n  broker_ext_port port_ = 0;\n};\n\n"
  )

  # PortState + dispatch.
  h.add(
    "namespace detail {\nstruct PortState {\n  const broker_ext_host* host = nullptr;\n" &
      "  broker_ext_port port = 0;\n  std::shared_ptr<" & iface & "> impl;\n"
  )
  for e in entries:
    let m = snakeToLowerCamel(e.wireName)
    case e.kind
    of enkRequest:
      let a = argsDecl(e)
      h.add(
        "  std::function<void(" & (if a.len > 0: a & ", " else: "") & "Responder<" &
          respType(e) & ">)> " & m & "Fn;\n"
      )
    of enkSignal:
      h.add("  std::function<void(" & sigValue(e) & ")> " & m & "Fn;\n")
    of enkEvent:
      discard
  h.add(
    "  std::mutex m;\n  std::unordered_map<broker_ext_call_id, std::stop_source> inflight;\n};\n\n" &
      "inline void replyBytes(const StatePtr& st, broker_ext_call_id id, int32_t status, const std::vector<uint8_t>& b) {\n" &
      "  st->host->reply(st->host->host, st->port, id, status, b.empty() ? nullptr : b.data(), b.size());\n}\n" &
      "inline std::stop_token track(const StatePtr& st, broker_ext_call_id id) {\n" &
      "  std::lock_guard<std::mutex> g(st->m);\n  return st->inflight[id].get_token();\n}\n" &
      "inline void untrack(const StatePtr& st, broker_ext_call_id id) {\n" &
      "  std::lock_guard<std::mutex> g(st->m);\n  st->inflight.erase(id);\n}\n\n" &
      "inline void invoke(void* user, broker_ext_call_id id, uint32_t idx, const char*, const uint8_t* buf, size_t len) {\n" &
      "  StatePtr st = *static_cast<StatePtr*>(user);\n  try {\n    switch (idx) {\n"
  )
  for i, e in entries:
    let m = snakeToLowerCamel(e.wireName)
    case e.kind
    of enkRequest:
      h.add("    case " & $i & ": {\n")
      var callArgs: seq[string]
      if e.args.len > 0:
        h.add("      auto a = decode<" & upperCamel(e.wireName) & "Args>(buf, len);\n")
        for (n, _) in e.args:
          callArgs.add("std::move(a." & n & ")")
      h.add("      Responder<" & respType(e) & "> r(st, id);\n")
      callArgs.add("std::move(r)")
      h.add(
        "      if (st->impl) st->impl->" & m & "(" & callArgs.join(", ") & ");\n" &
          "      else if (st->" & m & "Fn) st->" & m & "Fn(" & callArgs.join(", ") &
          ");\n" &
          "      else r.err(\"not implemented by plugin\");\n      break;\n    }\n"
      )
    of enkSignal:
      h.add("    case " & $i & ": {\n")
      if e.payloadType == "void":
        h.add(
          "      if (st->impl) st->impl->" & m & "();\n      else if (st->" & m &
            "Fn) st->" & m & "Fn();\n      break;\n    }\n"
        )
      else:
        h.add(
          "      auto v = decode<" & valueType(e) & ">(buf, len);\n" &
            "      if (st->impl) st->impl->" & m & "(std::move(v));\n      else if (st->" &
            m & "Fn) st->" & m & "Fn(std::move(v));\n      break;\n    }\n"
        )
    of enkEvent:
      discard
  h.add(
    "    default:\n      if (id != 0) replyBytes(st, id, BROKER_EXT_REPLY_ERR, {});\n    }\n" &
      "  } catch (const std::exception& ex) {\n" &
      "    if (id != 0) { std::string m = ex.what(); replyBytes(st, id, BROKER_EXT_REPLY_ERR, std::vector<uint8_t>(m.begin(), m.end())); }\n" &
      "  } catch (...) {\n    if (id != 0) { std::string m = \"plugin threw\"; replyBytes(st, id, BROKER_EXT_REPLY_ERR, std::vector<uint8_t>(m.begin(), m.end())); }\n  }\n}\n\n" &
      "inline void cancel(void* user, broker_ext_call_id id) {\n" &
      "  StatePtr st = *static_cast<StatePtr*>(user);\n  std::lock_guard<std::mutex> g(st->m);\n" &
      "  auto it = st->inflight.find(id);\n  if (it != st->inflight.end()) it->second.request_stop();\n}\n\n" &
      "inline void release(void* user) { delete static_cast<StatePtr*>(user); }\n" &
      "} // namespace detail\n\n"
  )

  # Port.
  h.add(
    "/// An open port of this plugin on one broker context. Closing (or\n" &
      "/// destroying) it withdraws every name it provides.\n" &
      "class Port {\npublic:\n  Port() = default;\n" &
      "  Port(Port&& o) noexcept : st_(std::move(o.st_)) {}\n" &
      "  Port& operator=(Port&& o) noexcept { if (this != &o) { close(); st_ = std::move(o.st_); } return *this; }\n" &
      "  Port(const Port&) = delete;\n  ~Port() { close(); }\n\n" &
      "  static Result<Port> open(const broker_ext_host* host, uint32_t ctx, std::shared_ptr<" &
      iface & "> impl) {\n" & "    auto st = std::make_shared<detail::PortState>();\n" &
      "    const uint32_t caps = impl->caps();\n    st->impl = std::move(impl);\n" &
      "    return openState(host, ctx, std::move(st), caps);\n  }\n\n" &
      "  int32_t provide(Api a) { return st_ ? st_->host->provide(st_->host->host, st_->port, apiName(a)) : BROKER_EXT_STALE; }\n" &
      "  int32_t withdraw(Api a) { return st_ ? st_->host->withdraw(st_->host->host, st_->port, apiName(a)) : BROKER_EXT_STALE; }\n" &
      "  int32_t provideAll() {\n    for (Api a : {"
  )
  var allApis: seq[string]
  for e in entries:
    if e.kind != enkEvent:
      allApis.add("Api::" & upperCamel(e.wireName))
  h.add(
    allApis.join(", ") &
      "}) {\n      int32_t rc = provide(a);\n      if (rc != BROKER_EXT_OK) return rc;\n    }\n    return BROKER_EXT_OK;\n  }\n" &
      "  Emitter emitter() const { return st_ ? Emitter(st_->host, st_->port) : Emitter(); }\n" &
      "  bool valid() const { return st_ != nullptr; }\n  broker_ext_port handle() const { return st_ ? st_->port : 0; }\n" &
      "  void close() { if (st_) { st_->host->close(st_->host->host, st_->port); st_.reset(); } }\n\n" &
      "private:\n  friend class Builder;\n" &
      "  static Result<Port> openState(const broker_ext_host* host, uint32_t ctx, detail::StatePtr st, uint32_t caps) {\n" &
      "    st->host = host;\n    auto* holder = new detail::StatePtr(st);\n" &
      "    broker_ext_impl impl{BROKER_EXT_ABI_VERSION, kPlugin, kSchemaHash, caps,\n" &
      "                         &detail::invoke, &detail::cancel, &detail::release, holder};\n" &
      "    broker_ext_port p = 0;\n    int32_t rc = host->open(host->host, ctx, &impl, &p);\n" &
      "    if (rc != BROKER_EXT_OK) { delete holder; return Result<Port>::err(\"open failed: \" + std::to_string(rc)); }\n" &
      "    st->port = p;\n    Port port;\n    port.st_ = std::move(st);\n    return Result<Port>::ok(std::move(port));\n  }\n" &
      "  detail::StatePtr st_;\n};\n\n"
  )

  # Builder.
  h.add(
    "/// C3: wire individual names with closures; `open` provides exactly the\n" &
      "/// names that were set (unset ones stay \"no provider\" on the Nim side).\n" &
      "class Builder {\npublic:\n"
  )
  for e in entries:
    let m = snakeToLowerCamel(e.wireName)
    case e.kind
    of enkRequest:
      let a = argsDecl(e)
      h.add(
        "  Builder& " & m & "(std::function<void(" & (if a.len > 0: a & ", "
        else: "") & "Responder<" & respType(e) & ">)> f) { st_->" & m &
          "Fn = std::move(f); set_.push_back(Api::" & upperCamel(e.wireName) &
          "); return *this; }\n"
      )
    of enkSignal:
      let on = "on" & upperCamel(e.wireName)
      h.add(
